/* ### 4. Operadores de Comparação (As Ferramentas de Medição)

Para decidir, você precisa comparar. Use estes símbolos:

- `==` : Compara o valor (perigoso, o JS tenta converter tipos).
- `===` : **O Padrão de Engenharia.** Compara o Valor **E** o Tipo (Número com Número, String com String). **Use sempre este.**
- `!=` e `!==` : Diferente de.
- `>` , `<` , `>=` , `<=` : Maior, menor, maior ou igual... */


/* ### 5. Operadores Lógicos (Decisões Complexas)

Às vezes, uma condição só não basta. Você precisa combinar sensores:

- **AND (`&&`):** Só é verdade se **TUDO** for verdade. (Ex: O motor só liga se tiver combustível **E** a bateria tiver carga).
- **OR (`||`):** É verdade se **PELO MENOS UM** for verdade. (Ex: O alarme toca se a porta abrir **OU** se o sensor de movimento detectar algo).
- **NOT (`!`):** Inverte o valor. Se é `true`, vira `false`. */







